import type { CompiledReportDataset } from './reportingTypes'

/**
 * Escapes a cell value for CSV and neutralizes spreadsheet formula injection risks.
 * Disables execution of formulas beginning with '=', '+', '-', '@', '\t', '\r'.
 */
function sanitizeCsvCell(val: any): string {
  if (val === null || val === undefined) return '""'
  let str = String(val).trim()

  // Neutralize spreadsheet formula injection
  if (/^[=+\-@\t\r]/.test(str)) {
    str = `'${str}`
  }

  // Escape internal double quotes
  str = str.replace(/"/g, '""')
  return `"${str}"`
}

/**
 * Trigger downloadable browser CSV export
 */
export function exportToCsv(report: CompiledReportDataset): void {
  const lines: string[] = []

  // Report Header Metadata
  lines.push(`"# PASHURAKSHA (पशुरक्षा) DIGITAL LIVESTOCK HEALTH REPORT"`)
  lines.push(`"Report Title: ${report.reportTitle.replace(/"/g, '""')}"`)
  lines.push(`"Document ID: ${report.documentId}"`)
  lines.push(`"Generated At: ${new Date(report.generatedAt).toLocaleString()}"`)
  lines.push(`"Generated By Role: ${report.generatedByRole.toUpperCase()}"`)
  lines.push(`"Reporting Window: ${report.dateWindowLabel}"`)
  lines.push(`"District Filter: ${report.filters.district} | Village: ${report.filters.village} | Species: ${report.filters.species}"`)
  lines.push(`""`)

  // Executive Summary Banner
  lines.push(`"--- EXECUTIVE SUMMARY ---"`)
  lines.push(`"Total Symptom Reports","${report.summary.totalSymptomReports}"`)
  lines.push(`"Total Unique Livestock","${report.summary.totalUniqueAnimals}"`)
  lines.push(`"Total Veterinary Cases","${report.summary.totalVeterinaryCases}"`)
  lines.push(`"Active Cases","${report.summary.activeCasesCount}"`)
  lines.push(`"Resolved Cases","${report.summary.resolvedCasesCount}"`)
  lines.push(`"Recorded Mortality Events","${report.summary.mortalityEventsCount}"`)
  lines.push(`"Potential Outbreak Clusters","${report.summary.potentialOutbreakClustersCount}"`)
  lines.push(`"Total Vaccination Records","${report.summary.totalVaccinationRecords}"`)
  lines.push(`""`)

  // Data Column Headers
  const headerLine = report.headers.map(sanitizeCsvCell).join(',')
  lines.push(headerLine)

  // Data Rows
  report.rows.forEach((row) => {
    const rowValues = Object.values(row).map(sanitizeCsvCell).join(',')
    lines.push(rowValues)
  })

  lines.push(`""`)
  lines.push(`"# Data Limitations & Methodology:"`)
  report.dataLimitations.forEach((lim) => {
    lines.push(`"# - ${lim.replace(/"/g, '""')}"`)
  })

  const csvContent = '\uFEFF' + lines.join('\r\n') // Include UTF-8 BOM for Excel Hindi/English rendering
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)

  const a = document.createElement('a')
  a.href = url
  a.download = `PashuRaksha_${report.category}_${new Date().toISOString().split('T')[0]}.csv`
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

/**
 * Trigger downloadable browser Excel format (.xls spreadsheet HTML table)
 */
export function exportToExcel(report: CompiledReportDataset): void {
  const tableRows = report.rows
    .map((row) => {
      const cells = Object.values(row)
        .map((cell) => {
          let str = String(cell ?? '').trim()
          if (/^[=+\-@\t\r]/.test(str)) str = `'${str}`
          return `<td style="border: 1px solid #CCCCCC; padding: 6px; font-family: sans-serif; font-size: 11px;">${str}</td>`
        })
        .join('')
      return `<tr>${cells}</tr>`
    })
    .join('')

  const headerCells = report.headers
    .map(
      (h) =>
        `<th style="background-color: #123C2A; color: #FFFFFF; border: 1px solid #123C2A; padding: 8px; font-family: sans-serif; font-size: 11px; text-align: left;">${h}</th>`
    )
    .join('')

  const excelHtml = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
    <head>
      <meta charset="utf-8" />
      <!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet><x:Name>PashuRaksha Report</x:Name><x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions></x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]-->
    </head>
    <body style="font-family: sans-serif;">
      <div style="background-color: #102A43; color: white; padding: 12px; font-size: 16px; font-weight: bold;">
        PASHURAKSHA (पशुरक्षा) &mdash; LIVESTOCK HEALTH SURVEILLANCE PLATFORM
      </div>
      <div style="padding: 8px 0; font-size: 13px; font-weight: bold; color: #1B5E3C;">
        ${report.reportTitle} &middot; ${report.documentId}
      </div>
      <div style="font-size: 11px; color: #555555; margin-bottom: 12px;">
        Generated on: ${new Date(report.generatedAt).toLocaleString()} | Scope: ${report.dateWindowLabel} | District: ${report.filters.district}
      </div>
      <table style="border-collapse: collapse; width: 100%;">
        <thead>
          <tr>${headerCells}</tr>
        </thead>
        <tbody>
          ${tableRows}
        </tbody>
      </table>
    </body>
    </html>
  `

  const blob = new Blob([excelHtml], { type: 'application/vnd.ms-excel;charset=utf-8;' })
  const url = URL.createObjectURL(blob)

  const a = document.createElement('a')
  a.href = url
  a.download = `PashuRaksha_${report.category}_${new Date().toISOString().split('T')[0]}.xls`
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

